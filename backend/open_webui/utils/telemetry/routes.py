_PATTERNS = {
    service: tuple(
        (
            re.compile(
                ''.join(
                    '[^/]+' if part.startswith('{') else re.escape(part) for part in re.split(r'(\{[^}]+\})', route)
                )
                + r'\Z'
            ),
            route,
        )
        for route in templates
    )
    for service, templates in TEMPLATES.items()
}


def route_template(path: str, service: str = 'soev-api') -> str:
    """Return the target's declared template, or a fixed unknown route marker."""
    clean = urlsplit(path).path
    return next(
        (route for pattern, route in _PATTERNS.get(service, ()) if pattern.fullmatch(clean)),
        'unmatched',
    )


def target_service(host: str) -> str:
    """Classify deployment hosts without exporting caller-controlled addresses."""
    label = host.split('.', 1)[0]
    if label in TEMPLATES:
        return label
    for suffix, service in (
        ('-pipeline-api', 'soev-pipeline'),
        ('-retrieval-api', 'soev-retrieval-api'),
        ('-connect-live', 'soev-connect'),
        ('-connect-bulk', 'soev-connect'),
        ('-connect', 'soev-connect'),
        ('-agents', 'soev-agents-api'),
        ('-sync', 'soev-sync'),
        ('-acl', 'soev-acl'),
        ('-web', 'soev-web'),
        ('-api', 'soev-api'),
    ):
        if label.endswith(suffix) or label == suffix.removeprefix('-'):
            return service
    return 'external'


def http_method(method: str) -> str:
    """Keep method metadata inside a fixed vocabulary."""
    return (
        method
        if method in {'GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS', 'CONNECT', 'WEBSOCKET'}
        else 'OTHER'
    )
