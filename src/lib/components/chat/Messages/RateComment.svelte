<script lang="ts">
	import { toast } from 'svelte-sonner';

	import { createEventDispatcher, onMount, getContext } from 'svelte';
	import { config, models } from '$lib/stores';
	import XMark from '$lib/components/icons/XMark.svelte';
	import ChevronRight from '$lib/components/icons/ChevronRight.svelte';

	const i18n = getContext<import('svelte/store').Readable<import('i18next').i18n>>('i18n');

	const dispatch = createEventDispatcher();

	export let message;
	export let show = false;

	let tags = [];

	let selectedReason = null;
	let comment = '';

	let detailedRating = null;
	let selectedModel = null;

	$: categoryTagsEnabled = $config?.features?.enable_feedback_category_tags ?? true;
	$: layer2Enabled = $config?.features?.enable_feedback_layer2 ?? true;
	$: layer3Enabled = $config?.features?.enable_feedback_layer3 ?? true;
	$: layer3Prompt = $config?.features?.feedback_layer3_prompt || '';

	type Definition = { id: string; labels: { nl: string; en: string } };
	$: language = $i18n.language.startsWith('nl') ? 'nl' : 'en';
	$: definitions = ($config?.features?.feedback_reasons ?? []) as Definition[];
	$: tagDefinitions = ($config?.features?.feedback_tags ?? []) as Definition[];
	$: reasons = definitions.map((item) => item.id);
	$: reasonLabels = Object.fromEntries(definitions.map((item) => [item.id, item.labels[language]]));

	$: if (message) {
		init();
	}

	const init = () => {
		if (!selectedReason) {
			selectedReason = message?.annotation?.reason ?? '';
		}

		if (!comment) {
			comment = message?.annotation?.comment ?? '';
		}

		tags = (message?.annotation?.tags ?? []).map((tag) => ({
			name: tag
		}));

		if (!detailedRating) {
			detailedRating = message?.annotation?.details?.rating ?? null;
		}
	};

	onMount(() => {
		if (message?.arena) {
			selectedModel = $models.find((m) => m.id === message.selectedModelId);
			toast.success(
				$i18n.t('This response was generated by "{{model}}"', {
					model: selectedModel ? (selectedModel?.name ?? selectedModel.id) : message.selectedModelId
				})
			);
		}
	});

	const saveHandler = () => {
		dispatch('save', {
			reason: selectedReason,
			comment: comment,
			tags: tags.map((tag) => tag.name),
			details: {
				rating: detailedRating
			}
		});

		toast.success($i18n.t('Thanks for your feedback!'));
		show = false;
	};
</script>

{#if message?.arena}
	<div class="text-xs font-normal pt-1.5 -mb-0.5">
		{$i18n.t('This response was generated by "{{model}}"', {
			model: selectedModel ? (selectedModel?.name ?? selectedModel.id) : message.selectedModelId
		})}
	</div>
{/if}

<div
	class=" my-2.5 rounded-xl px-4 py-3 border border-gray-100/30 dark:border-gray-850/30"
	id="message-feedback-{message.id}"
>
	<div class="flex justify-between items-center">
		<div class="text-sm font-normal">{$i18n.t('How would you rate this response?')}</div>

		<!-- <div class=" text-sm">{$i18n.t('Tell us more:')}</div> -->

		<button
			aria-label={$i18n.t('Close feedback')}
			on:click={() => {
				show = false;
			}}
		>
			<XMark className={'size-4'} />
		</button>
	</div>

	<div class="w-full overflow-x-auto">
		<div class="relative mx-auto min-w-[19rem] max-w-80">
			<div class="mt-1.5 grid grid-cols-10 gap-1 pb-2">
				<!-- 1-10 scale -->
				{#each Array.from({ length: 10 }).map((_, i) => i + 1) as rating}
					<button
						aria-label={$i18n.t('Rate {{rating}} out of 10', { rating })}
						class="aspect-square w-full text-sm border border-gray-100/30 dark:border-gray-850/30 hover:bg-gray-50 dark:hover:bg-gray-850 {detailedRating ===
						rating
							? 'bg-gray-100 dark:bg-gray-800'
							: ''} transition rounded-full disabled:cursor-not-allowed disabled:text-gray-500 disabled:bg-white dark:disabled:bg-gray-900"
						on:click={() => {
							detailedRating = rating;
						}}
						disabled={message?.annotation?.rating === -1 ? rating > 5 : rating < 6}
					>
						{rating}
					</button>
				{/each}
			</div>

			<div class="sticky top-0 bottom-0 left-0 right-0 flex justify-between text-xs">
				<div>
					1 - {$i18n.t('Awful')}
				</div>

				<div>
					10 - {$i18n.t('Amazing')}
				</div>
			</div>
		</div>
	</div>

	{#if layer2Enabled}
		<div>
			{#if reasons.length > 0}
				<div class="text-sm mt-1.5 font-normal">{$i18n.t('Why?')}</div>

				<div class="flex flex-wrap gap-1.5 text-sm mt-1.5">
					{#each reasons as reason}
						<button
							class="px-3 py-0.5 border border-gray-100/30 dark:border-gray-850/30 hover:bg-gray-50 dark:hover:bg-gray-850 {selectedReason ===
							reason
								? 'bg-gray-100 dark:bg-gray-800'
								: ''} transition rounded-xl"
							on:click={() => {
                                selectedReason = selectedReason === reason ? null : reason;
							}}
						>
                            {reasonLabels[reason]}
						</button>
					{/each}
				</div>
			{/if}
		</div>
	{/if}

	{#if layer3Enabled}
		<div class="mt-2">
			{#if $config?.features?.enable_v2_threads}
				<p class="text-xs text-gray-500 mb-1">
					{$i18n.t('Your comments are visible to tenant admins.')}
				</p>
			{/if}
			<textarea
				bind:value={comment}
				class="w-full text-sm px-1 py-2 bg-transparent outline-hidden resize-none rounded-xl"
				placeholder={layer3Prompt || $i18n.t('Feel free to add specific details')}
				aria-label={$i18n.t('Additional feedback comments')}
				rows="3"
			/>
		</div>
	{/if}

	<div class="mt-2 gap-1.5 flex justify-between">
		{#if categoryTagsEnabled}
			<div class="flex items-end group">
				{#each tagDefinitions as definition (definition.id)}
					<label class="flex items-center gap-1 text-xs">
						<input
							type="checkbox"
							checked={tags.some((tag) => tag.name === definition.id)}
							disabled={tags.length >= 16 && !tags.some((tag) => tag.name === definition.id)}
							on:change={(event) => {
								tags = event.currentTarget.checked
									? [...tags, { name: definition.id }]
									: tags.filter((tag) => tag.name !== definition.id);
							}}
						/>
						{definition.labels[language]}
					</label>
				{/each}
			</div>
		{:else}
			<div></div>
		{/if}

		<button
			class="px-3.5 py-1.5 text-sm font-normal bg-black hover:bg-gray-900 text-white dark:bg-white dark:text-black dark:hover:bg-gray-100 transition rounded-full"
			on:click={() => {
				saveHandler();
			}}
		>
			{$i18n.t('Save')}
		</button>
	</div>

	{#if $config?.features.enable_community_sharing && message?.model}
		<div class="mt-3 pt-3 border-t border-gray-100/30 dark:border-gray-850/30">
			<a
				href={`https://openwebui.com/models?q=${encodeURIComponent(message.model)}`}
				target="_blank"
				class="flex cursor-pointer items-center justify-between hover:bg-gray-50 dark:hover:bg-gray-850 w-full px-3 py-2 rounded-xl transition"
			>
				<div class="self-center">
					<div class="text-sm font-normal">
						{$i18n.t('Leave a public review for {{modelName}}', { modelName: message.model })}
					</div>
					<div class="text-xs text-gray-500">
						{$i18n.t('Help the community discover great models')}
					</div>
				</div>
				<ChevronRight className="size-4" />
			</a>
		</div>
	{/if}
</div>
